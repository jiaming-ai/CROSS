def slim(v, nd=3):
    return None if v is None else round(v, nd)


def build_replays(B, L):
    out, catalog = {}, {"generated": B["generated"], "commit": B["commit"], "mapping": [], "localization": []}
    t1_cache = {}

    def t1_runs(dataset, scene):
        if (dataset, scene) not in t1_cache:
            t1_cache[(dataset, scene)] = load_runs(f"t1_{dataset}_{scene}")
        return t1_cache[(dataset, scene)]

    def gt_path(dataset, scene, seq):
        for r in t1_runs(dataset, scene):
            if r.get("sequence") == seq and r.get("g"):
                return r["g"]
        return None

    for dataset, scene, seq, title, sub in T1_SEQUENCES:
        runs = [r for r in t1_runs(dataset, scene) if r.get("sequence") == seq]
        g = gt_path(dataset, scene, seq)
        items = []
        for r in runs:
            if (r["system"], r["setup"]) not in {tuple(o) for o in B["order"]}:
                continue  # hidden systems (not in the tables)
            items.append({"system": r["system"], "setup": r["setup"], "ate": slim(r.get("ate_rmse")),
                          "completeness": slim(r.get("completeness"), 3), "failed": bool(r.get("failed")),
                          "align": r.get("align"), "e": r.get("e"),
                          **({"odom_fallback": r["odom_fallback"]} if r.get("odom_fallback") else {})})
        sid = f"t1-{dataset}-{seq.replace('/', '-')}"
        out[sid] = {"id": sid, "track": "t1", "dataset": dataset, "scene": scene, "sequence": seq, "title": title,
                    "subtitle": sub, "thresholds": B["datasets"][dataset]["thresholds"], "gt": g, "runs": items}
        catalog["mapping"].append({"id": sid, "dataset": dataset, "title": title, "subtitle": sub})
    splits = {d: dict(v) for d, v in B["splits"].items()}
    for dataset, scene, title in T2_SCENES:
        runs = load_runs(f"t2_{dataset}_{scene}")
        sp = splits[dataset][scene]
        queries = []
        for q in sp["queries"]:
            items = []
            for r in runs:
                if r.get("query") != q or (r["system"], r["setup"]) not in {tuple(o) for o in B["order"]}:
                    continue
                thr = r.get("thresholds") or sp["thresholds"]
                items.append({"system": r["system"], "setup": r["setup"], "status": r.get("status"),
                              "lr": [slim(r.get(f"lr@{t:g}")) for t in thr], "est_frac": slim(r.get("est_frac")),
                              "c": r.get("c"),
                              **({"odom_fallback": r["odom_fallback"]} if r.get("odom_fallback") else {})})
            queries.append({"query": q, "gt": gt_path(dataset, scene, q), "runs": items})
        sid = f"t2-{dataset}-{scene}"
        out[sid] = {"id": sid, "track": "t2", "dataset": dataset, "scene": scene, "title": title, "map": sp["map"],
                    "map_gt": gt_path(dataset, scene, sp["map"]), "thresholds": sp["thresholds"], "queries": queries}
        catalog["localization"].append({"id": sid, "dataset": dataset, "title": title, "map": sp["map"],
                                        "queries": sp["queries"]})
    catalog["systems"] = L["systems"]
    catalog["families"] = FAMILIES
    catalog["setups"] = SETUPS
    out["index"] = catalog
    return out


