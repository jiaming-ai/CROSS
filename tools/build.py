#!/usr/bin/env python3
"""Build the generated parts of the CROSS site. Standard library only.

    python3 tools/build.py           # rebuild everything
    python3 tools/build.py --check   # exit 1 if a page or data file is out of date (nothing written)
    python3 tools/build.py --page docs/index.html   # only that page (plus data files and sitemap)

1. Data: assets/data/leaderboard.json and assets/data/replays/*.json, read from the published benchmark page
   (benchmark/data.js and benchmark/runs/*.js). That page is generated by the code repository's
   benchmark/publish_page.sh; after it has been republished, run this script so the summary pages agree with it.
2. Numbers: the text of every element with a data-num="key" attribute in the pages is replaced by the value of
   `key` (python3 tools/build.py --list-nums prints them all).
3. Partials: the shared header and footer (tools/partials/*.html) between <!-- partial:NAME --> markers.
4. sitemap.xml.
"""
import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SITE_URL = "https://jiaming.im/CROSS/"
BENCH = ROOT / "benchmark"
DATA = ROOT / "assets/data"

# page file -> (key used by the partials for aria-current, path to the site root, sitemap priority)
PAGES = {
    "index.html": ("home", "", "1.0"),
    "leaderboard/index.html": ("leaderboard", "../", "0.9"),
    "replays/index.html": ("replays", "../", "0.7"),
    "docs/index.html": ("docs", "../", "0.9"),
    "v1/index.html": ("papers", "../", "0.8"),
}
EXTRA_SITEMAP = [("benchmark/", "0.6")]  # the detailed results page (generated elsewhere, listed here)

FAMILIES = {  # family key -> display name, in the order the pages list them
    "cross": "CROSS", "orbslam3": "ORB-SLAM3", "rtabmap": "RTAB-Map", "mast3r_slam": "MASt3R-SLAM",
    "vggt_slam": "VGGT-SLAM 2.0", "lingbot_map": "LingBot-Map", "amb3r_slam": "AMB3R-SLAM",
}
SETUPS = {"rgbd": "RGB-D", "stereo": "Stereo", "mono": "Mono"}


def family_of(system):
    return "cross" if system.startswith("cross") else next(f for f in FAMILIES if system.startswith(f))


def load_js_object(path, prefix):
    """The JSON value assigned or passed in a generated .js file (window.X = {...}; or window.F("name", [...]);)."""
    text = path.read_text()
    if not text.startswith(prefix):
        raise SystemExit(f"{path}: unexpected format (expected it to start with {prefix!r})")
    return text


def load_bench():
    text = load_js_object(BENCH / "data.js", "window.BENCH = ")
    return json.loads(text[text.index("{"):text.rstrip().rstrip(";").rindex("}") + 1])


def load_runs(chunk):
    text = load_js_object(BENCH / "runs" / f"{chunk}.js", "window.BENCH_RUNS(")
    return json.loads(text[text.index("["):text.rstrip().rstrip(";").rstrip(")").rindex("]") + 1])


# ------------------------------------------------------------------------------------------------ leaderboard
FAIL_RE = re.compile(r"\((\d+)/(\d+) ✗\)")


def parse_cell(text, pair):
    """A summary-table cell -> {"v": value(s) or None, "fail": "k/N" or None, "text": original}."""
    t = text.strip()
    out = {"text": t, "v": None, "fail": None}
    m = FAIL_RE.search(t)
    if m:
        out["fail"] = f"{m.group(1)}/{m.group(2)}"
        t = FAIL_RE.sub("", t).strip()
    elif re.fullmatch(r"\d+/\d+ ✗", t):          # every sequence failed: no value
        out["fail"] = t.replace(" ✗", "")
        return out
    if t in ("", "·", "✗", "n/a", "–"):
        if t == "✗":
            out["fail"] = "all"
        return out
    t = t.replace("%", "").strip()
    if pair:
        lo, hi = [float(x) for x in t.split("/")]
        out["v"] = [lo, hi]
    else:
        out["v"] = float(t)
    return out


def inputs_of(sysdef):
    if sysdef.get("odom") == "vio":
        return "vio"
    if sysdef.get("uses_odometry"):
        return "odometry"
    if sysdef.get("uses_imu"):
        return "imu"
    return "camera"


def build_leaderboard(B):
    systems = {}
    for key, d in B["systems"].items():
        fam = family_of(key)
        systems[key] = {"label": d["label"], "family": fam, "inputs": inputs_of(d),
                        "map_reuse": d.get("map_reuse"), "upper_bound": key == "lingbot_map"}
    tasks = {}
    spec = {  # summary key -> (task id, column datasets, pair values, higher is better)
        "rs": ("t3", ["openloris", "rover", "simchange", "overall"], True, True),
        "lr": ("t2", ["openloris", "rover", "simchange", "overall"], True, True),
        "ate": ("t1", ["kitti", "openloris", "rover", "overall", "scale"], False, False),
    }
    for key, title, note, md in B["summary"]:
        tid, cols, pair, higher = spec[key]
        lines = [l for l in md.splitlines() if l.startswith("| ") and not l.startswith("| system") and not l.startswith("|---")]
        rows = []
        for (system, setup), line in zip(B["order"], lines):
            cells = [c for c in line.split("|")[1:-1]]
            label = cells[0].strip()
            vals = {col: parse_cell(c, pair) for col, c in zip(cols, cells[1:])}
            rows.append({"system": system, "setup": setup, "label": label, "family": family_of(system),
                         "inputs": systems[system]["inputs"], "cells": vals})
        tasks[tid] = {"title": title, "note": note, "cols": cols, "higher": higher, "rows": rows}
    datasets = {}
    for name, cfg in B["datasets"].items():
        stats = B["datastats"].get(name, {})
        n_sessions = sum(len(v) for v in stats.values())
        n_trials = sum(s.get("trials", 0) for v in stats.values() for s in v.values())
        datasets[name] = {"environment": cfg["environment"], "thresholds": cfg["thresholds"],
                          "odometry": cfg.get("odometry"), "scenes": cfg["scenes"],
                          "sessions": n_sessions, "t3_trials": n_trials}
    return {"generated": B["generated"], "commit": B["commit"], "n_runs": B["n_runs"],
            "families": FAMILIES, "setups": SETUPS, "systems": systems, "datasets": datasets, "tasks": tasks}


def best_rows(task, pred=lambda r: True, col="overall", idx=1):
    """Rows with a value in `col` that satisfy pred, best first (idx: 1 = larger threshold of a pair)."""
    rows = [r for r in task["rows"] if pred(r) and r["cells"][col]["v"] is not None and not r["cells"][col]["fail"]]
    val = (lambda r: r["cells"][col]["v"][idx]) if isinstance(rows[0]["cells"][col]["v"], list) else (lambda r: r["cells"][col]["v"])
    return sorted(rows, key=val, reverse=task["higher"]), val


def numbers(L):
    """Named values for data-num elements in the pages (all strings, formatted for display)."""
    N = {"runs": f"{L['n_runs']:,}", "baselines": str(len(FAMILIES) - 1), "generated": L["generated"][:10],
         "commit": L["commit"]}
    pct = lambda v: f"{round(v * 100)}%"
    N["datasets"] = str(len(L["datasets"]))
    N["t3_trials"] = f"{sum(d['t3_trials'] for d in L['datasets'].values()):,}"
    N["sessions"] = str(sum(d["sessions"] for d in L["datasets"].values()))
    for tid in ("t3", "t2"):
        T = L["tasks"][tid]
        row = lambda s, st: next(r for r in T["rows"] if r["system"] == s and r["setup"] == st)
        # the configuration the pages headline: stereo + odometry (the recommended mode, stereo_wheel)
        ref = row("cross_stereo", "stereo")
        for col in ("openloris", "rover", "simchange", "overall"):
            N[f"{tid}.cross.{col}"] = pct(ref["cells"][col]["v"][1])
        cam = row("cross_stereo_vo", "stereo")
        N[f"{tid}.cross_camera.overall"] = pct(cam["cells"]["overall"]["v"][1])
        bl, val = best_rows(T, lambda r: r["family"] != "cross")
        N[f"{tid}.best_baseline.overall"] = pct(val(bl[0]))
        N[f"{tid}.best_baseline.name"] = FAMILIES[bl[0]["family"]]
        cl, val = best_rows(T, lambda r: r["family"] in ("orbslam3", "rtabmap"))
        N[f"{tid}.best_classical.overall"] = pct(val(cl[0]))
        N[f"{tid}.best_classical.name"] = FAMILIES[cl[0]["family"]]
        for col in ("rover", "openloris", "simchange"):
            b, val = best_rows(T, lambda r: r["family"] != "cross", col)
            N[f"{tid}.best_baseline.{col}"] = pct(val(b[0]))
            N[f"{tid}.best_baseline.{col}.name"] = FAMILIES[b[0]["family"]]
        same = next(r for r in T["rows"] if r["system"] == "rtabmap" and r["setup"] == "stereo")  # same inputs as ref
        N[f"{tid}.rtabmap_same_inputs.overall"] = pct(same["cells"]["overall"]["v"][1])
    T = L["tasks"]["t1"]
    cr, val = best_rows(T, lambda r: r["family"] == "cross")
    N["t1.cross.best.overall"] = f"{val(cr[0]):.2f}%"
    ref = next(r for r in T["rows"] if r["system"] == "cross_stereo" and r["setup"] == "stereo")
    N["t1.cross.overall"] = f"{ref['cells']['overall']['v']:.2f}%"
    rt = next(r for r in T["rows"] if r["system"] == "rtabmap" and r["setup"] == "stereo")
    N["t1.rtabmap_same_inputs.overall"] = f"{rt['cells']['overall']['v']:.2f}%"
    return N


# ------------------------------------------------------------------------------------------------ replays
# Mapping replays (T1): one file per sequence. Localization replays (T2): one file per scene, all its queries.
T1_SEQUENCES = [
    ("rover", "campus_large", "campus_large_night_2024-09-24_3", "ROVER campus at night", "outdoor robot, 280 m, night"),
    ("rover", "campus_large", "campus_large_winter_2024-01-27", "ROVER campus in winter", "outdoor robot, 295 m, snow"),
    ("kitti", "00", "00", "KITTI 00", "car, 3.7 km, loops"),
    ("kitti", "05", "05", "KITTI 05", "car, 2.2 km, loops"),
    ("openloris", "corridor", "corridor1-1", "OpenLORIS corridor", "indoor robot, 222 m"),
    ("openloris", "market", "market1-1", "OpenLORIS market", "indoor robot, 150 m"),
    ("openloris", "home", "home1-1", "OpenLORIS home", "indoor robot, 40 m"),
    ("simchange", "hssd_restaurant", "hssd_restaurant/map", "SimChange restaurant", "simulated, 146 m"),
]
T2_SCENES = [("rover", "campus_large", "ROVER campus"), ("openloris", "corridor", "OpenLORIS corridor"),
             ("openloris", "market", "OpenLORIS market"), ("openloris", "home", "OpenLORIS home"),
             ("openloris", "cafe", "OpenLORIS cafe"), ("openloris", "office", "OpenLORIS office")]


def slim(v, nd=3):
    return None if v is None else round(v, nd)


def build_replays(B, L):
    out, catalog = {}, {"generated": B["generated"], "commit": B["commit"], "mapping": [], "localization": []}
    t1_cache = {}

    def t1_runs(dataset, scene):
        if (dataset, scene) not in t1_cache:
            t1_cache[(dataset, scene)] = load_runs(f"t1_{dataset}_{scene}")
        return t1_cache[(dataset, scene)]

    def gt_path(dataset, scene, seq):
        for r in t1_runs(dataset, scene):
            if r.get("sequence") == seq and r.get("g"):
                return r["g"]
        return None

    for dataset, scene, seq, title, sub in T1_SEQUENCES:
        runs = [r for r in t1_runs(dataset, scene) if r.get("sequence") == seq]
        g = gt_path(dataset, scene, seq)
        items = []
        for r in runs:
            if (r["system"], r["setup"]) not in {tuple(o) for o in B["order"]}:
                continue  # hidden systems (not in the tables)
            items.append({"system": r["system"], "setup": r["setup"], "ate": slim(r.get("ate_rmse")),
                          "completeness": slim(r.get("completeness"), 3), "failed": bool(r.get("failed")),
                          "align": r.get("align"), "e": r.get("e")})
        sid = f"t1-{dataset}-{seq.replace('/', '-')}"
        out[sid] = {"id": sid, "track": "t1", "dataset": dataset, "scene": scene, "sequence": seq, "title": title,
                    "subtitle": sub, "thresholds": B["datasets"][dataset]["thresholds"], "gt": g, "runs": items}
        catalog["mapping"].append({"id": sid, "dataset": dataset, "title": title, "subtitle": sub})
    splits = {d: dict(v) for d, v in B["splits"].items()}
    for dataset, scene, title in T2_SCENES:
        runs = load_runs(f"t2_{dataset}_{scene}")
        sp = splits[dataset][scene]
        queries = []
        for q in sp["queries"]:
            items = []
            for r in runs:
                if r.get("query") != q or (r["system"], r["setup"]) not in {tuple(o) for o in B["order"]}:
                    continue
                thr = r.get("thresholds") or sp["thresholds"]
                items.append({"system": r["system"], "setup": r["setup"], "status": r.get("status"),
                              "lr": [slim(r.get(f"lr@{t:g}")) for t in thr], "est_frac": slim(r.get("est_frac")),
                              "c": r.get("c")})
            queries.append({"query": q, "gt": gt_path(dataset, scene, q), "runs": items})
        sid = f"t2-{dataset}-{scene}"
        out[sid] = {"id": sid, "track": "t2", "dataset": dataset, "scene": scene, "title": title, "map": sp["map"],
                    "map_gt": gt_path(dataset, scene, sp["map"]), "thresholds": sp["thresholds"], "queries": queries}
        catalog["localization"].append({"id": sid, "dataset": dataset, "title": title, "map": sp["map"],
                                        "queries": sp["queries"]})
    catalog["systems"] = L["systems"]
    catalog["families"] = FAMILIES
    catalog["setups"] = SETUPS
    out["index"] = catalog
    return out


# ------------------------------------------------------------------------------------------------ pages
def render_partial(name, page_key, root):
    tpl = (ROOT / "tools/partials" / f"{name}.html").read_text().strip("\n")
    tpl = tpl.replace("{root}", root)
    # mark the current page: <a ... data-key="docs"> -> aria-current="page"
    return re.sub(r'data-key="([a-z0-9-]+)"',
                  lambda m: m.group(0) + (' aria-current="page"' if m.group(1) == page_key else ""), tpl)


def apply_partials(html, page_key, root):
    def rep(m):
        name = m.group(1)
        return f"<!-- partial:{name} -->\n{render_partial(name, page_key, root)}\n<!-- /partial:{name} -->"
    return re.sub(r"<!-- partial:([a-z-]+) -->.*?<!-- /partial:\1 -->", rep, html, flags=re.S)


def apply_numbers(html, N, page):
    def rep(m):
        key = m.group(2)
        if key not in N:
            raise SystemExit(f"{page}: unknown data-num key {key!r} (python3 tools/build.py --list-nums)")
        return f"{m.group(1)}{N[key]}{m.group(3)}"
    return re.sub(r'(<(?:span|strong|b|em|td|dd|div|p)\b[^>]*\bdata-num="([^"]+)"[^>]*>)[^<]*(</)', rep, html)


def sitemap():
    urls = [(("" if p == "index.html" else p.replace("index.html", "")), prio) for p, (_, _, prio) in PAGES.items()
            if (ROOT / p).is_file()] + EXTRA_SITEMAP
    body = "\n".join(f"  <url><loc>{SITE_URL}{u}</loc><priority>{prio}</priority></url>" for u, prio in urls)
    return f'<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n{body}\n</urlset>\n'


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="report out-of-date files, write nothing (exit 1 if any)")
    ap.add_argument("--list-nums", action="store_true", help="print the data-num keys and values")
    ap.add_argument("--page", action="append", metavar="FILE",
                    help="only this page (e.g. docs/index.html; repeatable); data files and the sitemap are still built")
    a = ap.parse_args()
    B = load_bench()
    L = build_leaderboard(B)
    N = numbers(L)
    if a.list_nums:
        for k, v in N.items():
            print(f"{k:42s} {v}")
        return
    files = {DATA / "leaderboard.json": json.dumps(L, separators=(",", ":"), ensure_ascii=False) + "\n"}
    for sid, obj in build_replays(B, L).items():
        files[DATA / "replays" / f"{sid}.json"] = json.dumps(obj, separators=(",", ":"), ensure_ascii=False) + "\n"
    for page, (key, root, _) in PAGES.items():
        p = ROOT / page
        if a.page and page not in a.page:
            continue
        if p.is_file():
            files[p] = apply_numbers(apply_partials(p.read_text(), key, root), N, page)
    files[ROOT / "sitemap.xml"] = sitemap()
    stale = []
    for path, text in files.items():
        if not path.is_file() or path.read_text() != text:
            stale.append(path.relative_to(ROOT))
            if not a.check:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(text)
    verb = "out of date" if a.check else "written"
    print(f"{len(stale)} file(s) {verb}" + (": " + ", ".join(map(str, stale)) if stale else ""))
    if a.check and stale:
        sys.exit(1)


if __name__ == "__main__":
    main()
