FAIL_RE = re.compile(r"\((\d+)/(\d+) ✗\)")


def parse_cell(text, pair):
    """A summary-table cell -> {"v": value(s) or None, "fail": "k/N" or None, "text": original}."""
    t = text.strip()
    out = {"text": t, "v": None, "fail": None}
    m = FAIL_RE.search(t)
    if m:
        out["fail"] = f"{m.group(1)}/{m.group(2)}"
        t = FAIL_RE.sub("", t).strip()
    elif re.fullmatch(r"\d+/\d+ ✗", t):          # every sequence failed: no value
        out["fail"] = t.replace(" ✗", "")
        return out
    if t in ("", "·", "✗", "n/a", "–"):
        if t == "✗":
            out["fail"] = "all"
        return out
    t = t.replace("%", "").strip()
    if pair:
        lo, hi = [float(x) for x in t.split("/")]
        out["v"] = [lo, hi]
    else:
        out["v"] = float(t)
    return out


def inputs_of(sysdef):
    if sysdef.get("odom") == "vio":
        return "vio"
    if sysdef.get("uses_odometry"):
        return "odometry"
    if sysdef.get("uses_imu"):
        return "imu"
    return "camera"


def build_leaderboard(B):
    systems = {}
    for key, d in B["systems"].items():
        fam = family_of(key)
        systems[key] = {"label": d["label"], "family": fam, "inputs": inputs_of(d),
                        "map_reuse": d.get("map_reuse"), "upper_bound": key == "lingbot_map"}
    tasks = {}
    spec = {  # summary key -> (task id, column datasets, pair values, higher is better)
        "rs": ("t3", ["openloris", "rover", "simchange", "overall"], True, True),
        "lr": ("t2", ["openloris", "rover", "simchange", "overall"], True, True),
        "ate": ("t1", ["kitti", "openloris", "rover", "overall", "scale"], False, False),
    }
    for key, title, note, md in B["summary"]:
        tid, cols, pair, higher = spec[key]
        lines = [l for l in md.splitlines() if l.startswith("| ") and not l.startswith("| system") and not l.startswith("|---")]
        rows = []
        for (system, setup), line in zip(B["order"], lines):
            cells = [c for c in line.split("|")[1:-1]]
            label = cells[0].strip()
            vals = {col: parse_cell(c, pair) for col, c in zip(cols, cells[1:])}
            rows.append({"system": system, "setup": setup, "label": label, "family": family_of(system),
                         "inputs": systems[system]["inputs"], "cells": vals})
        tasks[tid] = {"title": title, "note": note, "cols": cols, "higher": higher, "rows": rows}
    # relocalization trials scored per row: systems without map persistence re-run the map session for every trial,
    # so they are scored on a subset of the trials
    scored = {}
    for chunk in B["chunks"]:
        if chunk.startswith("t3_"):
            for r in load_runs(chunk):
                key = (r["system"], r["setup"])
                scored[key] = scored.get(key, 0) + (r.get("n_trials") or 0)
    for r in tasks["t3"]["rows"]:
        r["trials"] = scored.get((r["system"], r["setup"]), 0)
    datasets = {}
    for name, cfg in B["datasets"].items():
        stats = B["datastats"].get(name, {})
        n_sessions = sum(len(v) for v in stats.values())
        n_trials = sum(s.get("trials", 0) for v in stats.values() for s in v.values())
        datasets[name] = {"environment": cfg["environment"], "thresholds": cfg["thresholds"],
                          "odometry": cfg.get("odometry"), "scenes": cfg["scenes"],
                          "sessions": n_sessions, "t3_trials": n_trials}
    return {"generated": B["generated"], "commit": B["commit"], "n_runs": B["n_runs"],
            "families": FAMILIES, "setups": SETUPS, "systems": systems, "datasets": datasets, "tasks": tasks}


def best_rows(task, pred=lambda r: True, col="overall", idx=1):
    """Rows with a value in `col` that satisfy pred, best first (idx: 1 = larger threshold of a pair)."""
    rows = [r for r in task["rows"] if pred(r) and r["cells"][col]["v"] is not None and not r["cells"][col]["fail"]]
    val = (lambda r: r["cells"][col]["v"][idx]) if isinstance(rows[0]["cells"][col]["v"], list) else (lambda r: r["cells"][col]["v"])
    return sorted(rows, key=val, reverse=task["higher"]), val


def numbers(L):
    """Named values for data-num elements in the pages (all strings, formatted for display)."""
    N = {"runs": f"{L['n_runs']:,}", "baselines": str(len(FAMILIES) - 1), "generated": L["generated"][:10],
         "commit": L["commit"]}
    pct = lambda v: f"{round(v * 100)}%"
    N["datasets"] = str(len(L["datasets"]))
    N["t3_trials"] = f"{sum(d['t3_trials'] for d in L['datasets'].values()):,}"
    N["sessions"] = str(sum(d["sessions"] for d in L["datasets"].values()))
    N["configurations"] = str(len(L["tasks"]["t3"]["rows"]))  # rows of the tables (system x setup)
    for name, d in L["datasets"].items():
        N[f"{name}.scenes"] = str(len(d["scenes"]))
        N[f"{name}.sessions"] = str(d["sessions"])
        N[f"{name}.t3_trials"] = f"{d['t3_trials']:,}"
    for tid in ("t3", "t2"):
        T = L["tasks"][tid]
        row = lambda s, st: next(r for r in T["rows"] if r["system"] == s and r["setup"] == st)
        # the configuration the pages headline: stereo + odometry (the recommended mode, stereo_wheel)
        ref = row("cross_stereo", "stereo")
        for col in ("openloris", "rover", "simchange", "overall"):
            N[f"{tid}.cross.{col}"] = pct(ref["cells"][col]["v"][1])
        cam = row("cross_stereo_vo", "stereo")  # cameras only: no odometry input
        for col in ("openloris", "rover", "simchange", "overall"):
            N[f"{tid}.cross_camera.{col}" if col != "overall" else f"{tid}.cross_camera.overall"] = pct(cam["cells"][col]["v"][1])
        best, val = best_rows(T, lambda r: r["family"] == "cross")  # CROSS's best configuration (the rankings' row)
        N[f"{tid}.cross.best.overall"] = pct(val(best[0]))
        bl, val = best_rows(T, lambda r: r["family"] != "cross")
        N[f"{tid}.best_baseline.overall"] = pct(val(bl[0]))
        N[f"{tid}.best_baseline.name"] = FAMILIES[bl[0]["family"]]
        # the best baseline's score is an upper bound when it has no relocalization step (LingBot-Map)
        N[f"{tid}.best_baseline.ub"] = (" (an upper bound: it has no relocalization step)"
                                        if L["systems"][bl[0]["system"]]["upper_bound"] else "")
        N[f"{tid}.best_baseline.ub_note"] = ", an upper bound" if L["systems"][bl[0]["system"]]["upper_bound"] else ""
        cl, val = best_rows(T, lambda r: r["family"] in ("orbslam3", "rtabmap"))
        N[f"{tid}.best_classical.overall"] = pct(val(cl[0]))
        N[f"{tid}.best_classical.name"] = FAMILIES[cl[0]["family"]]
        for col in ("rover", "openloris", "simchange"):
            b, val = best_rows(T, lambda r: r["family"] != "cross", col)
            N[f"{tid}.best_baseline.{col}"] = pct(val(b[0]))
            N[f"{tid}.best_baseline.{col}.name"] = FAMILIES[b[0]["family"]]
            N[f"{tid}.best_baseline.{col}.ub_note"] = ", an upper bound" if L["systems"][b[0]["system"]]["upper_bound"] else ""
        same = next(r for r in T["rows"] if r["system"] == "rtabmap" and r["setup"] == "stereo")  # same inputs as ref
        N[f"{tid}.rtabmap_same_inputs.overall"] = pct(same["cells"]["overall"]["v"][1])
    T = L["tasks"]["t1"]
    cr, val = best_rows(T, lambda r: r["family"] == "cross")
    N["t1.cross.best.overall"] = f"{val(cr[0]):.2f}%"
    ref = next(r for r in T["rows"] if r["system"] == "cross_stereo" and r["setup"] == "stereo")
    N["t1.cross.overall"] = f"{ref['cells']['overall']['v']:.2f}%"
    cam = next(r for r in T["rows"] if r["system"] == "cross_stereo_vo" and r["setup"] == "stereo")
    N["t1.cross_camera.overall"] = f"{cam['cells']['overall']['v']:.2f}%"
    rt = next(r for r in T["rows"] if r["system"] == "rtabmap" and r["setup"] == "stereo")
    N["t1.rtabmap_same_inputs.overall"] = f"{rt['cells']['overall']['v']:.2f}%"
    return N


