def family_of(system):
    return "cross" if system.startswith("cross") else next(f for f in FAMILIES if system.startswith(f))


def load_js_object(path, prefix):
    """The JSON value assigned or passed in a generated .js file (window.X = {...}; or window.F("name", [...]);)."""
    text = path.read_text()
    if not text.startswith(prefix):
        raise SystemExit(f"{path}: unexpected format (expected it to start with {prefix!r})")
    return text


def load_bench():
    text = load_js_object(BENCH / "data.js", "window.BENCH = ")
    return json.loads(text[text.index("{"):text.rstrip().rstrip(";").rindex("}") + 1])


def load_runs(chunk):
    text = load_js_object(BENCH / "runs" / f"{chunk}.js", "window.BENCH_RUNS(")
    return json.loads(text[text.index("["):text.rstrip().rstrip(";").rstrip(")").rindex("]") + 1])


