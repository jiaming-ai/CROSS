def render_partial(name, page_key, root):
    tpl = (ROOT / "tools/partials" / f"{name}.html").read_text().strip("\n")
    tpl = tpl.replace("{root}", root)
    # mark the current page: <a ... data-key="docs"> -> aria-current="page"; "papers" links to a section of the hub,
    # so on a paper page it is the current item of the nav, not the current page
    def mark(m):
        if m.group(1) != page_key:
            return m.group(0)
        return m.group(0) + (' aria-current="true"' if page_key == "papers" else ' aria-current="page"')
    return re.sub(r'data-key="([a-z0-9-]+)"', mark, tpl)


def apply_partials(html, page_key, root):
    def rep(m):
        name = m.group(1)
        return f"<!-- partial:{name} -->\n{render_partial(name, page_key, root)}\n<!-- /partial:{name} -->"
    return re.sub(r"<!-- partial:([a-z-]+) -->.*?<!-- /partial:\1 -->", rep, html, flags=re.S)


def apply_gen(text, L, page):
    """Fill every <!-- gen:NAME --> ... <!-- /gen:NAME --> block with GEN_BLOCKS[NAME], at the marker's indent."""
    def rep(m):
        ind, name = m.group(1), m.group(2)
        if name not in GEN_BLOCKS:
            raise SystemExit(f"{page}: unknown generated block {name!r} (tools/build.py GEN_BLOCKS)")
        body = "\n".join(ind + line if line else line for line in GEN_BLOCKS[name](L).split("\n"))
        return f"{ind}<!-- gen:{name} -->\n{body}\n{ind}<!-- /gen:{name} -->"
    return re.sub(r"^([ \t]*)<!-- gen:([a-z0-9-]+) -->.*?<!-- /gen:\2 -->", rep, text, flags=re.S | re.M)


def apply_numbers(html, N, page):
    def rep(m):
        key = m.group(2)
        if key not in N:
            raise SystemExit(f"{page}: unknown data-num key {key!r} (python3 tools/build.py --list-nums)")
        return f"{m.group(1)}{N[key]}{m.group(3)}"
    return re.sub(r'(<(?:span|strong|b|em|td|dd|div|p)\b[^>]*\bdata-num="([^"]+)"[^>]*>)[^<]*(</)', rep, html)


def sitemap():
    urls = [(("" if p == "index.html" else p.replace("index.html", "")), prio) for p, (_, _, prio) in PAGES.items()
            if (ROOT / p).is_file()] + EXTRA_SITEMAP
    body = "\n".join(f"  <url><loc>{SITE_URL}{u}</loc><priority>{prio}</priority></url>" for u, prio in urls)
    return f'<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n{body}\n</urlset>\n'


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="report out-of-date files, write nothing (exit 1 if any)")
    ap.add_argument("--list-nums", action="store_true", help="print the data-num keys and values")
    ap.add_argument("--page", action="append", metavar="FILE",
                    help="only this page (e.g. docs/index.html; repeatable); data files and the sitemap are still built")
    a = ap.parse_args()
    B = load_bench()
    L = build_leaderboard(B)
    N = numbers(L)
    if a.list_nums:
        for k, v in N.items():
            print(f"{k:42s} {v}")
        return
    files = {DATA / "leaderboard.json": json.dumps(L, separators=(",", ":"), ensure_ascii=False) + "\n"}
    for sid, obj in build_replays(B, L).items():
        files[DATA / "replays" / f"{sid}.json"] = json.dumps(obj, separators=(",", ":"), ensure_ascii=False) + "\n"
    for page, (key, root, _) in PAGES.items():
        p = ROOT / page
        if a.page and page not in a.page:
            continue
        if p.is_file():
            files[p] = apply_numbers(apply_gen(apply_partials(p.read_text(), key, root), L, page), N, page)
    files[ROOT / "sitemap.xml"] = sitemap()
    stale = []
    for path, text in files.items():
        if not path.is_file() or path.read_text() != text:
            stale.append(path.relative_to(ROOT))
            if not a.check:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(text)
    verb = "out of date" if a.check else "written"
    print(f"{len(stale)} file(s) {verb}" + (": " + ", ".join(map(str, stale)) if stale else ""))
    if a.check and stale:
        sys.exit(1)


if __name__ == "__main__":
    main()
